// Writes public/THIRD_PARTY_LICENSES.txt: the license notices of every runtime dependency that
// can end up in the extension bundle (MIT, Zlib and Apache-2.0 require them in distributed
// copies; the minifier strips the in-source headers).
//
// Usage: node scripts/generate-licenses.mjs [--check]
//   --check  exit 1 when the committed file is out of date (CI / release check).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'public', 'THIRD_PARTY_LICENSES.txt');
const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.(md|txt|markdown))?$/i;

/** Finds a package directory the way Node resolves it from `fromDir`. */
function resolvePackage(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

const seen = new Map();
function walk(name, fromDir) {
  // Type definitions are never bundled.
  if (name.startsWith('@types/')) return;
  const dir = resolvePackage(name, fromDir);
  if (!dir) throw new Error(`Cannot resolve ${name} from ${fromDir}`);
  const pkg = readJson(path.join(dir, 'package.json'));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) return;
  const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
  const texts = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim());
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'UNKNOWN';
  seen.set(key, { name: pkg.name, version: pkg.version, license, homepage: pkg.homepage ?? pkg.repository?.url ?? '', texts });
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, dir);
}

const rootPkg = readJson(path.join(root, 'package.json'));
for (const dep of Object.keys(rootPkg.dependencies ?? {})) walk(dep, root);

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const lines = [
  'Third-party software in Fast Confluence Exporter',
  '',
  'This extension bundles the following open-source packages. Their license notices follow.',
  'Generated by scripts/generate-licenses.mjs — do not edit by hand.',
  '',
];
for (const e of entries) {
  lines.push('='.repeat(78), `${e.name} ${e.version} — ${e.license}`, ...(e.homepage ? [e.homepage] : []), '-'.repeat(78));
  if (e.texts.length) lines.push(...e.texts.flatMap((t) => [t, '']));
  else lines.push(`Licensed under ${e.license}. (No license file is included in the package.)`, '');
}
const content = lines.join('\n').replace(/\n+$/, '\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== content) {
    console.error('public/THIRD_PARTY_LICENSES.txt is out of date. Run: npm run licenses');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_LICENSES.txt is up to date (${entries.length} packages).`);
} else {
  fs.writeFileSync(outFile, content);
  console.log(`Wrote ${path.relative(root, outFile)} (${entries.length} packages).`);
}
